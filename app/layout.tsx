import type { Metadata } from "next";
import localFont from "next/font/local";
import ScrollReset from "../components/ScrollReset";
import "./globals.css";

// All fonts are stored in /fonts (latin, variable weight) instead of next/font/google,
// so builds never depend on downloading from Google Fonts. A failed download there
// broke a production build on 2026-10-31.
const geistSans = localFont({
  src: "../fonts/Geist/Geist-Variable.woff2",
  variable: "--font-geist-sans",
  weight: "100 900",
});

const geistMono = localFont({
  src: "../fonts/Geist/GeistMono-Variable.woff2",
  variable: "--font-geist-mono",
  weight: "100 900",
});

// Logo-matched pair: a classical roman serif like "BAYDOUN", a light geometric sans like "WATCHES".
const cormorant = localFont({
  src: "../fonts/Cormorant_Garamond/cormorant-garamond-latin-wght-normal.woff2",
  variable: "--font-cormorant",
  weight: "300 700",
  display: "swap",
});

const jost = localFont({
  src: "../fonts/Jost/jost-latin-wght-normal.woff2",
  variable: "--font-jost",
  weight: "100 900",
  display: "swap",
});

const playfair = localFont({
  src: [
    {
      path: "../fonts/Playfair_Display/static/PlayfairDisplay-Medium.ttf",
      weight: "700",
      style: "normal",
    },
    {
      path: "../fonts/Playfair_Display/static/PlayfairDisplay-Black.ttf",
      weight: "800",
      style: "normal",
    },
  ],
  variable: "--font-playfair",
  display: "swap",
});

export const metadata: Metadata = {
  title: "Baydoun Watches",
  description: "Generated by Moe Jardani",
};

export default function RootLayout({
  children,
}: Readonly<{ children: React.ReactNode }>) {
  return (
    <html
      suppressHydrationWarning
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} ${playfair.variable} ${cormorant.variable} ${jost.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col"><ScrollReset />{children}</body>
    </html>
  );
}
